const KOREAN_HOLIDAYS: ReadonlySet<string> = new Set([
  ...HOLIDAYS_2026,
  ...HOLIDAYS_2027,
  ...HOLIDAYS_2028,
])

/** 'en-CA' yields ISO-like YYYY-MM-DD, resolved in the Asia/Seoul calendar day. */
const SEOUL_DATE_FMT = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Asia/Seoul",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
})

export function toSeoulDateString(date: Date): string {
  return SEOUL_DATE_FMT.format(date)
}

/**
 * Returns true when the given instant falls on a Korean public holiday in
 * Asia/Seoul. Years outside the hardcoded range always return false.
 */
export function isKoreanHoliday(date: Date): boolean {
  return KOREAN_HOLIDAYS.has(toSeoulDateString(date))
}
